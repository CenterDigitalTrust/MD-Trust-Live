import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
try {
  // Generate Dart constants from the exact catalog used by the Twitch bundle.
  const messages=JSON.parse(await readFile(new URL('shared/translations.json',root),'utf8'));
  for(const [key,values] of Object.entries(messages)) {
    if(values.length!==7||values.some(value=>typeof value!=='string'||!value.trim()))throw new Error(`Incomplete translation: ${key}`);
    if(values.some(value=>value.includes('$')))throw new Error(`Escape Dart interpolation before using $: ${key}`);
  }
  await mkdir(new URL('app/lib/l10n/',root),{recursive:true});
  await writeFile(new URL('app/lib/l10n/messages.dart',root),'// Generated by tools/generate-locales.mjs; edit shared/translations.json.\nconst messages = <String, List<String>> '+JSON.stringify(messages,null,2)+';\n');
  const languages=['en','es','de','fr','ru','uk','ja'];
  for(const [index,language] of languages.entries()) {
    // Android service notifications share the same translation source as Flutter.
    const directory=new URL(`app/android/app/src/main/res/values${language==='en'?'':'-'+language}/`,root);
    await mkdir(directory,{recursive:true});
    const escape=value=>value.replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll("'","\\'").replaceAll('"','\\"');
    const body=['active','intro','stop'].map(key=>`  <string name="mdtl_${key}" formatted="false">${escape(messages[key][index])}</string>`).join('\n');
    await writeFile(new URL('strings.xml',directory),'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'+body+'\n</resources>\n');
  }
  console.info(`Generated ${Object.keys(messages).length} messages in seven languages.`);
} catch(error){console.error('Locale generation failed:',error.message);process.exitCode=1;}
